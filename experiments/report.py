def preds(n):
    return np.load(results.RESULTS / "preds" / f"{n}_test.npy").astype(np.int64)


def drop_ci(name, n_boot=2000):
    """Paired bootstrap 95% CI of the accuracy drop (FP32 - model), in points."""
    a = preds("fp32") == te_y
    b = preds(name) == te_y
    rng = np.random.default_rng(0)
    idx = rng.integers(0, len(a), size=(n_boot, len(a)))
    d = 100 * (a[idx].mean(1) - b[idx].mean(1))
    return 100 * (a.mean() - b.mean()), np.percentile(d, 2.5), np.percentile(d, 97.5)


def lat_ms(t, model):
    return lat["by_threads"][str(t)]["models"][model]["median_ms"]


